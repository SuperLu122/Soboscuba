#!/usr/bin/env python3
"""Generates www/js/styles.js from the colour tables in docs/original-spec.md
(section 12). The first entry, dark_mode, is the default, as in the original."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
spec = (root / 'docs' / 'original-spec.md').read_text()

def table(after):
    i = spec.index(after)
    rows = []
    for line in spec[i:].splitlines()[1:]:
        if line.startswith('|'):
            rows.append([c.strip() for c in line.strip('|').split('|')])
        elif rows:
            break
    return rows[2:]  # drop header and separator

world = table('Table 12.1')
ui = {r[0]: r[1:] for r in table('Table 12.2')}
pal = {r[0]: ['#' + c for c in r[3].split()] for r in table('Table 12.3')}

LIGHT = {'light_mode', '2048', 'candy', 'game_boy', 'high_contrast_light', 'ink', 'maple', 'matcha', 'sakura', 'sky', 'solarpunk', 'terracotta'}
styles = []
for r in world:
    sid = r[1]
    styles.append({
        'id': sid, 'name': sid.replace('_', ' '), 'free': sid in ('dark_mode', 'light_mode'), 'light': sid in LIGHT,
        'bg': r[3], 'structure': r[4], 'oob': r[5], 'recess': r[6], 'fill': r[7],
        'special': r[8], 'danger': r[9], 'marker': r[10], 'label': r[3],
        'palette': pal[r[2]], 'ui': ui[sid],
    })
out = ('/* Generated by tools/gen-styles.py from docs/original-spec.md section 12. Do not edit. */\n'
       '(function (SB) {\n  \'use strict\';\n  SB.STYLES = ' + json.dumps(styles, indent=1) + ';\n'
       '  SB.UI_KEYS = ["highlight", "highlightHover", "highlightDisabled", "background", "backgroundHover", '
       '"backgroundPressed", "panel", "panelHover", "panelDisabled"];\n'
       '})(window.SB = window.SB || {});\n')
(root / 'www' / 'js' / 'styles.js').write_text(out)
print(len(styles), 'styles')
